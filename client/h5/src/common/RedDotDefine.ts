declare global {
    /**
     * 红点逻辑
     */
    interface IRedDotController {
        /**
         * 单例
         */
        ins: IRedDotController;
        /**
         * 添加红点
         * @param key
         * @param parent
         */
        add(key: string, parent: string);
        /**
         * 绑定组件
         * @param key
         * @param comp
         * @param isUp
         */
        bind(key: string, comp: Laya.UIComponent);
        /**
         * 解除组件
         * @param key
         * @param isUp
         */
        unbind(key);
        /**
         * 删除红点key
         * @param key
         */
        del(key: string);
        /**
         * 更新红点状态
         * @param key
         * @param state
         */
        up(key: string, state: number);

        /**
         * 获取红点状态
         * @param key
         */
        get(key: string): number;
    }
}
